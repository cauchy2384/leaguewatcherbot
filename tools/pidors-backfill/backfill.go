// Backfill planning and application for pidors.json → pidor_rolls.
//
// The algorithm is described in ADR-011 §"Backfill strategy":
//
//	Within a channel, sort user_id values lexicographically ascending.
//	The i-th user (0-indexed) gets rolled_on = DATE '1970-01-01' + i days,
//	and times_rolled = the lifetime count from pidors.json.
//
// Before applying any planned rows, the tool snapshots the current
// pidor_rolls contents into a timestamped backup table and TRUNCATEs
// the main table — all in the same transaction. This makes the final
// state deterministic: the table contents always equal what the
// backfill computed from pidors.json. Restore on failure is:
//
//	TRUNCATE pidor_rolls;
//	INSERT INTO pidor_rolls SELECT * FROM pidor_rolls_backup_…;
//	DROP TABLE pidor_rolls_backup_…;
package main

import (
	"context"
	"fmt"
	"leaguewatcher/internal/leaguewatcher/pidorjson"
	"regexp"
	"sort"
	"time"

	"github.com/jackc/pgx/v5/pgxpool"
)

// syntheticEpoch is the base date for backfilled rows. Any row with
// rolled_on in this era is unambiguously not a live roll.
var syntheticEpoch = time.Date(1970, time.January, 1, 0, 0, 0, 0, time.UTC)

// planRow is a computed but unwritten pidor_rolls row.
type planRow struct {
	ChannelID   string
	UserID      string
	UserName    string
	RolledOn    time.Time
	TimesRolled int
}

// computePlan converts pidors.json Stats into pidor_rolls rows.
// Returns the rows to insert (in deterministic order) plus warnings
// for entries that were skipped (bad input). Warnings do NOT cause
// the run to fail — the choice is to import what's valid rather than
// abort on a single corrupt entry.
func computePlan(p *pidorjson.Pidor) ([]planRow, []string) {
	if p == nil || len(p.Stats) == 0 {
		return nil, nil
	}

	var rows []planRow
	var warnings []string

	// Iterate channels in deterministic order for stable output and
	// consistent test expectations.
	channelIDs := make([]string, 0, len(p.Stats))
	for ch := range p.Stats {
		channelIDs = append(channelIDs, ch)
	}
	sort.Strings(channelIDs)

	for _, channelID := range channelIDs {
		stats := p.Stats[channelID]

		// Filter + sort user IDs. Lexicographic sort is deliberate:
		// gives the same date assignment on every run regardless of
		// iteration order or map shuffling.
		type userEntry struct {
			id    string
			name  string
			count int
		}
		users := make([]userEntry, 0, len(stats))
		for userID, s := range stats {
			if s.Count <= 0 {
				warnings = append(warnings,
					fmt.Sprintf("channel=%s user=%s: skipped (count=%d ≤ 0)",
						channelID, userID, s.Count))
				continue
			}
			if s.Name == "" {
				warnings = append(warnings,
					fmt.Sprintf("channel=%s user=%s: skipped (empty name)",
						channelID, userID))
				continue
			}
			users = append(users, userEntry{id: userID, name: s.Name, count: s.Count})
		}
		sort.Slice(users, func(i, j int) bool { return users[i].id < users[j].id })

		for i, u := range users {
			rows = append(rows, planRow{
				ChannelID:   channelID,
				UserID:      u.id,
				UserName:    u.name,
				RolledOn:    syntheticEpoch.AddDate(0, 0, i),
				TimesRolled: u.count,
			})
		}
	}

	return rows, warnings
}

// backupNameFormat is the date-time format used for the snapshot backup
// table name. UTC, sortable, no special characters — safe to interpolate
// into SQL as an identifier.
const backupNameFormat = "pidor_rolls_backup_20060102_150405_utc"

// defaultBackupName generates the timestamped name used when the caller
// does not override.
func defaultBackupName(now time.Time) string {
	return now.UTC().Format(backupNameFormat)
}

// safeIdentifierPattern whitelists what we allow as a table name to
// interpolate into CREATE TABLE. The autogenerated defaultBackupName
// always matches; the pattern is a defence-in-depth check against
// accidentally passing user-controlled strings in the future.
var safeIdentifierPattern = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)

// applyPlan snapshots the source table into a timestamped backup,
// truncates the source, then inserts every planned row, all within
// a single transaction. Returns the number of rows inserted plus the
// number of rows that were truncated (for operator visibility).
//
// `sourceTable` is normally "pidor_rolls" but is parameterised so
// the integration test can target an isolated mirror table instead
// of production data. It is validated by safeIdentifierPattern
// before being interpolated into SQL.
//
// Because the source is empty at insert time, every planned row
// guarantees insertion; this function does not return a "skipped"
// counter.
//
// On error everything rolls back: no backup, no truncate, no rows.
func applyPlan(ctx context.Context, pool *pgxpool.Pool, sourceTable, backupName string, rows []planRow) (inserted, truncated int, err error) {
	if !safeIdentifierPattern.MatchString(sourceTable) {
		return 0, 0, fmt.Errorf("source table %q is not a safe identifier", sourceTable)
	}
	if !safeIdentifierPattern.MatchString(backupName) {
		return 0, 0, fmt.Errorf("backup name %q is not a safe identifier", backupName)
	}

	tx, err := pool.Begin(ctx)
	if err != nil {
		return 0, 0, fmt.Errorf("begin transaction: %w", err)
	}
	defer func() {
		if err != nil {
			_ = tx.Rollback(ctx)
		}
	}()

	// 1. Snapshot existing source table into a backup table.
	//    Copies data + column types, deliberately NOT the constraints —
	//    the backup is a raw data snapshot for recovery. Restore means
	//    truncating source and re-inserting from the backup.
	createBackupSQL := fmt.Sprintf("CREATE TABLE %s AS TABLE %s", backupName, sourceTable)
	if _, err := tx.Exec(ctx, createBackupSQL); err != nil {
		return 0, 0, fmt.Errorf("create backup %q: %w", backupName, err)
	}

	// 2. Truncate the source table so inserts are guaranteed to land.
	//    Capture the previous row count first for operator visibility.
	if err := tx.QueryRow(ctx,
		fmt.Sprintf("SELECT count(*) FROM %s", sourceTable)).Scan(&truncated); err != nil {
		return 0, 0, fmt.Errorf("count previous rows: %w", err)
	}
	if _, err := tx.Exec(ctx,
		fmt.Sprintf("TRUNCATE TABLE %s", sourceTable)); err != nil {
		return 0, 0, fmt.Errorf("truncate: %w", err)
	}

	// 3. Insert all planned rows into the source table.
	insertTarget := fmt.Sprintf(
		"INSERT INTO %s (channel_id, user_id, user_name, rolled_on, times_rolled) VALUES ($1,$2,$3,$4,$5)",
		sourceTable)
	for _, r := range rows {
		if _, err := tx.Exec(ctx, insertTarget,
			r.ChannelID, r.UserID, r.UserName, r.RolledOn, r.TimesRolled); err != nil {
			return 0, 0, fmt.Errorf("insert channel=%s user=%s rolled_on=%s: %w",
				r.ChannelID, r.UserID, r.RolledOn.Format("2006-01-02"), err)
		}
		inserted++
	}

	if err := tx.Commit(ctx); err != nil {
		return 0, 0, fmt.Errorf("commit: %w", err)
	}
	return inserted, truncated, nil
}
